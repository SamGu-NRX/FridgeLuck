"""Render results/tables.md from results/metrics.json.

Read-only over the metrics; deterministic output (fixed formatting, no
timestamps) so the committed tables byte-match the committed metrics.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

RESULTS = Path(__file__).resolve().parents[1] / "results"


def fmt(x: float, nd: int = 3) -> str:
    return f"{x:.{nd}f}"


def ci(a: dict, key: str, nd: int = 3) -> str:
    b = a["bootstrap"][key]
    return f"[{b['lo']:.{nd}f}, {b['hi']:.{nd}f}]"


def main() -> int:
    m = json.loads((RESULTS / "metrics.json").read_text())
    lines: list[str] = []
    add = lines.append

    add("# Part 0 — headline tables (generated by experiments/tables.py)")
    add("")
    add(f"Episodes: {m['episodes']} · bootstrap B={m['bootstrap']['b']} "
        f"seed={m['bootstrap']['seed']} · determinism self-check: "
        f"{'pass' if m['determinism_selfcheck'] else 'FAIL'}")
    add("")

    # --- the headline contrast: proxy vs truth on identical episodes ---
    add("## 1. The headline contrast — same episodes, two reward channels")
    add("")
    add("Both arms replay identical inputs through the identical port; only the "
        "reward channel differs (`proxy` = what the as-built app stores, "
        "`truth` = independent correctness). ECE/Brier are computed against "
        "**truth**, so a lower value is genuinely better calibrated.")
    add("")
    add("| Arm | ECE vs truth (95% CI) | Pooled-signal ECE | Brier vs truth | Episodes until trailing-4 mode-error ≤ 0.25 |")
    add("| --- | --- | --- | --- | --- |")
    for name in ["beta-proxy", "beta-truth"]:
        a = m["arms"][name]
        met = a["metrics"]
        stab = met["stabilization_episode_trailing4"]
        stab_s = "never (≤ bar throughout)" if stab == 0 else str(stab)
        add(f"| `{name}` | {fmt(met['overall_ece_vs_truth'])} {ci(a, 'overall_ece_vs_truth')} "
            f"| {fmt(met['pooled_signal_ece_vs_truth'])} | {fmt(met['overall_brier_vs_truth'])} | {stab_s} |")
    add("")

    # --- telemetry gap ---
    add("## 2. Telemetry gap — what the shipped dashboard reports vs reality")
    add("")
    add("| Arm | `calibrationSnapshots` reports | Actual raw-vs-truth error | Understatement |")
    add("| --- | --- | --- | --- |")
    gap = m["telemetry_gap"]
    for name, g in gap.items():
        reported = g["pooled"]["avg_abs_error_vs_stored"]
        actual = g["pooled"]["avg_abs_error_vs_truth"]
        ratio = actual / reported if reported else float("inf")
        add(f"| `{name}` | {fmt(reported)} | {fmt(actual)} | {fmt(ratio, 1)}× |")
    add("")

    # --- decision quality ---
    add("## 3. Decision quality (modes vs truth)")
    add("")
    add("| Arm | exact (right/wrong) | review_required | estimate_only on correct | Mode-error rate |")
    add("| --- | --- | --- | --- | --- |")
    for name, a in m["arms"].items():
        d = a["metrics"]["decision"]
        add(f"| `{name}` | {d['exact_n']} ({d['exact_right']}/{d['exact_wrong']}) "
            f"| {d['review_n']} | {d['estimate_fn']} | {fmt(d['mode_error_rate'])} |")
    add("")
    add("Hard-fail episodes are excluded by design (estimate_only is the specified "
        "contract there, independent of confidence quality).")
    add("")

    # --- sweeps ---
    add("## 4. Prior and decay sweeps (truth channel)")
    add("")
    add("| Arm | ECE vs truth (95% CI) | Pooled-signal ECE | Brier | estimate_only on correct | Mode-error rate |")
    add("| --- | --- | --- | --- | --- | --- |")
    for name in ["beta-truth", "prior-doubled", "prior-flat-10-5", "prior-jeffreys",
                 "decay-0.990", "decay-0.999", "decay-1.00"]:
        a = m["arms"][name]
        met = a["metrics"]
        d = met["decision"]
        add(f"| `{name}` | {fmt(met['overall_ece_vs_truth'])} {ci(a, 'overall_ece_vs_truth')} "
            f"| {fmt(met['pooled_signal_ece_vs_truth'])} | {fmt(met['overall_brier_vs_truth'])} "
            f"| {d['estimate_fn']} | {fmt(d['mode_error_rate'])} |")
    add("")

    # --- alternatives ---
    add("## 5. Learned calibrators on the same episodes")
    add("")
    add("| Calibrator | Split | ECE vs truth | Brier | exact (r/w) | review | estimate_only on correct |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for name, a in m["alternatives"].items():
        if name == "note":
            continue
        for split in ["in_sample", "leave_one_out"]:
            s = a[split]
            d = s["decision"]
            add(f"| {name} | {split.replace('_', '-')} | {fmt(s['ece_vs_truth'])} | {fmt(s['brier_vs_truth'])} "
                f"| {d['exact_n']} ({d['exact_right']}/{d['exact_wrong']}) | {d['review_n']} | {d['estimate_fn']} |")
    add("")

    # --- strawman ---
    add("## 6. Base-rate strawman (calibration floor)")
    add("")
    s = m["base_rate_strawman"]
    add(f"Expanding mean of prior episode truths: ECE {fmt(s['ece_vs_truth'])}, "
        f"Brier {fmt(s['brier_vs_truth'])}. The Beta arms beat this on both — "
        "the informative priors' shrinkage is doing real work at n=12.")
    add("")

    # --- extended replay ---
    add("## 7. Extended replay — is the exact gate reachable at all?")
    add("")
    add("The 12 episodes replayed 1×/2×/4×/8× (12/24/48/96 updates) under both "
        "channels. `max overall` is the largest geometric-fusion overall score "
        "ever observed; the exact gate needs overall ≥ 0.84 **and** min-adjusted ≥ 0.62.")
    add("")
    add("| Passes | Arm | First exact-mode episode | exact decisions (r/w) | Max overall observed |")
    add("| --- | --- | --- | --- | --- |")
    for p, arms in m["extended_first_exact"].items():
        for arm, d in arms.items():
            fe = d["first_exact_episode"] if d["first_exact_episode"] is not None else "never"
            add(f"| {p.replace('passes-', '')} | `{arm}` | {fe} | {d['exact_n']} "
                f"({d['exact_right']}/{d['exact_wrong']}) | {fmt(d['max_overall'], 4)} |")
    add("")

    # --- drift ---
    add("## 8. Drift recovery")
    add("")
    add("### 8a. PR #53 changed-family histories (50 seeds, truth flip mid-history)")
    add("")
    cf = m["drift"]["changed-family"]
    add(f"Reached the bar (trailing-4 mode-error ≤ {cf['bar']}, held): {cf['reached']}/{cf['n_seeds']}. "
        f"Median scans-to-recovery among reachers: {cf['median_scans_to_recovery']} "
        f"(min {cf['min']}, max {cf['max']}). Never reached: {cf['not_reached']}/{cf['n_seeds']}.")
    add("")
    add("### 8b. Synthetic capability drop on reverse-meal (drop after episode "
        f"{m['drift']['drop_after_episode_index']}, episodes 1–{m['drift']['drop_after_episode_index']} healthy)")
    add("")
    add("| Factor | Arm | Pre-drop mode-error rate | Scans until mode-error back under bar |")
    add("| --- | --- | --- | --- |")
    for factor_key, arms in m["drift"]["arms"].items():
        for arm, d in arms.items():
            rec = d["recovery_episodes"]
            rec_s = ("immediate (1)" if rec == 1 else
                     ("never (bar unreachable post-drop)" if rec is None else str(rec)))
            add(f"| {factor_key.replace('factor-', '×')} | `{arm}` "
                f"| {fmt(d['pre_drop_mode_error_rate'])} | {rec_s} |")
    add("")
    add("Interpretation guard: after a severe drop, refusal of correct episodes "
        "is the *correct* conservative response — the bar counts it as error "
        "anyway. Read 8b as a utility statement (share of correct actions the "
        "system still serves while degraded), not as a bug.")
    add("")

    # --- held-out ---
    add("## 9. Held-out spec rows (collision groups reported groupwise)")
    add("")
    for arm, s in m["heldout"]["summary"].items():
        modes = s["modes_on_labeled"]
        pairs = ", ".join(f"{k.replace('RM-', '')}={v[0]}" for k, v in sorted(modes.items()))
        add(f"- `{arm}`: exact-on-wrong {s['exact_on_wrong']}, estimate-on-correct "
            f"{s['estimate_on_correct']}; modes — {pairs}")
    add("")
    add("Byte-equivalent collision groups (RM-03/04/13, RM-06/16) receive "
        "identical modes by construction — the spec forbids demanding separation "
        "inside a group; no arm violated that.")
    add("")

    (RESULTS / "tables.md").write_text("\n".join(lines))
    print(f"wrote {RESULTS / 'tables.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
