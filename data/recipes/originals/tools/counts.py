#!/usr/bin/env python3
"""Count accepted recipes in data/recipes/originals/ and regenerate REPORT.md.

Counts a recipe as ACCEPTED only when it passes validate.py's checks: parseable
RS recipe, rights-clear source_ref, suite linter clean, craft layer clean.

Usage:
    python3 tools/counts.py                 # print the report block
    python3 tools/counts.py --write-report  # splice the block into REPORT.md
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import originals_common as oc  # noqa: E402
from validate import check_recipe, suite_allergens  # noqa: E402

BEGIN = "<!-- COUNTS:BEGIN -->"
END = "<!-- COUNTS:END -->"


def accepted_recipes():
    rs, bands, rights = oc.load_suite_modules()
    allergens = suite_allergens()
    claim_defs = allergens["claims"]
    conv_all, _ = oc.load_conversions(None)
    scanner_suite = rs.AllergenScanner(allergens)
    bundled_seen: dict[str, str] = {}
    rows = []
    for part in sorted(oc.PARTS):
        prefix, family, allowed = oc.PARTS[part]
        rights_statuses, _m = oc.load_rights_manifests(part)
        strict = oc.StrictScanner(oc.load_compound_entries(part))
        recipes, bad = oc.discover_recipes(part)
        for path, r in recipes:
            hard = list(rs.lint_recipe(
                r, cuisines=bands.CUISINE_SET, meal_slots=bands.SLOT_SET,
                conversions=conv_all, allergen_scan=scanner_suite))
            craft_hard, _soft = check_recipe(
                r["id"], r, part=part, prefix=prefix, family=family,
                allowed_cuisines=allowed, suite_cuisines=bands.CUISINE_SET,
                scanner_suite=scanner_suite, scanner_strict=strict,
                claim_defs=claim_defs, rights_statuses=rights_statuses,
                bundled_ids_seen=bundled_seen)
            hard += craft_hard
            rows.append((part, r, not hard))
    return rows


def build_block() -> str:
    rows = accepted_recipes()
    lines: list[str] = ["### Generated counts", ""]
    lines.append("_Accepted = rights-clear + suite lint + craft layer clean. "
                 "Generated by `data/recipes/originals/tools/counts.py`._")
    lines.append("")
    total = {}
    for part in sorted(oc.PARTS):
        subset = [(r, ok) for p, r, ok in rows if p == part]
        total[part] = (len(subset), sum(1 for _, ok in subset if ok))
    grand = sum(a for _, a in total.values())
    lines.append(f"**Total accepted: {grand}** (target >= 600)")
    lines.append("")
    lines.append("| Part | Files | Accepted |")
    lines.append("|---|---|---|")
    for part in sorted(oc.PARTS):
        n, a = total[part]
        lines.append(f"| {part} | {n} | {a} |")
    lines.append("")

    cats: dict[str, Counter] = {
        "family": Counter(), "cuisine": Counter(), "cuisine_detail": Counter(),
        "meal_slot": Counter(), "time": Counter(), "claims": Counter(),
        "tags": Counter(), "use_it_up": Counter(), "budget": Counter(),
        "servings": Counter(),
    }
    for part, r, ok in rows:
        if not ok:
            continue
        cats["family"][r.get("family", "?")] += 1
        cats["cuisine"][r.get("cuisine", "?")] += 1
        cats["cuisine_detail"][str(r.get("cuisine_detail", "?"))] += 1
        for s in r.get("meal_slots", []):
            cats["meal_slot"][s] += 1
        m = r.get("minutes", 0)
        band = "<=15" if m <= 15 else "16-30" if m <= 30 else "31-60" if m <= 60 else ">60"
        cats["time"][band] += 1
        for c in r.get("claims", []):
            cats["claims"][c.get("claim", "?")] += 1
        for t in r.get("tags", []):
            cats["tags"][t] += 1
        sv = r.get("servings", "?")
        cats["servings"]["1" if sv == 1 else "2" if sv == 2 else "3-4" if sv <= 4 else "5+"] += 1
        cost = (r.get("cost_per_serving_usd") or {}).get("value")
        if isinstance(cost, (int, float)):
            band = "<$1.25" if cost < 1.25 else "$1.25-2.50" if cost <= 2.50 else ">$2.50"
            cats["budget"][band] += 1
        for t in r.get("tags", []):
            if t.startswith("use-it-up:"):
                cats["use_it_up"][t.split(":", 1)[1]] += 1

    lines.append("Claim counts: " + ", ".join(f"{k}={v}" for k, v in sorted(cats["claims"].items())))
    lines.append("Tags: " + ", ".join(f"{k}={v}" for k, v in sorted(cats["tags"].items())))
    lines.append("Use-it-up targets: " + ", ".join(f"{k}={v}" for k, v in sorted(cats["use_it_up"].items())))
    lines.append("Budget bands: " + ", ".join(f"{k}={v}" for k, v in sorted(cats["budget"].items())))
    lines.append("Time bands: " + ", ".join(f"{k}={v}" for k, v in sorted(cats["time"].items())))
    lines.append("Servings: " + ", ".join(f"{k}={v}" for k, v in sorted(cats["servings"].items())))
    lines.append("")

    n_files = len(rows)
    n_ok = sum(1 for _, _, ok in rows if ok)
    lines.append(f"Corpus status: {n_files} files, {n_ok} accepted. "
                 f"Every recipe carries test_status='untested' - none of these have "
                 f"been cooked or platform-audited yet; the claims are machine-verified "
                 f"against USDA values and the compound-allergen table, not kitchen-verified.")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write-report", action="store_true")
    args = ap.parse_args()
    block = build_block()
    print(block)
    if args.write_report:
        report = oc.originals_dir() / "REPORT.md"
        if report.is_file():
            text = report.read_text()
            if BEGIN in text and END in text:
                start = text.index(BEGIN) + len(BEGIN)
                end = text.index(END)
                report.write_text(text[:start] + "\n" + block + "\n" + text[end:])
                print(f"\nwrote {report}")
            else:
                print(f"\n{report} lacks {BEGIN} markers; not modified")
        else:
            report.write_text(f"# Originals corpus report\n\n{BEGIN}\n{block}\n{END}\n")
            print(f"\ncreated {report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
