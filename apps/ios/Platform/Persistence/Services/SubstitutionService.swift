// MARK: - Substitution Reason

/// Why this substitution exists — displayed as badges in the UI.
enum SubstitutionReason: String, Sendable, CaseIterable {
  case vegan = "Vegan"
  case dairyFree = "Dairy-Free"
  case glutenFree = "Gluten-Free"
  case vegetarian = "Vegetarian"
  case lighter = "Lighter"
  case lowCarb = "Low-Carb"
  case similar = "Similar Flavor"

  var icon: String {
    switch self {
    case .vegan: "leaf.fill"
    case .dairyFree: "drop.degreesign.slash"
    case .glutenFree: "xmark.seal.fill"
    case .vegetarian: "leaf"
    case .lighter: "scalemass"
    case .lowCarb: "chart.bar.xaxis.ascending"
    case .similar: "arrow.triangle.swap"
    }
  }

  /// Map dietary restriction IDs to relevant reasons.
  ///
  /// With the simplified diet model (classic/pescatarian/vegetarian/vegan/keto),
  /// only the single selected diet is passed in the restrictions set.
  /// Gluten-free and dairy-free are now handled by the allergen system.
  static func reasons(forRestrictions restrictions: Set<String>) -> Set<SubstitutionReason> {
    var result: Set<SubstitutionReason> = []

    if restrictions.contains("vegan") {
      result.formUnion([.vegan, .dairyFree, .vegetarian])
    } else if restrictions.contains("vegetarian") || restrictions.contains("pescatarian") {
      result.insert(.vegetarian)
    }

    if restrictions.contains("keto") {
      result.insert(.lowCarb)
    }

    // Legacy support: if older profiles still have these IDs, honor them
    if restrictions.contains("dairy_free") {
      result.insert(.dairyFree)
    }
    if restrictions.contains("gluten_free") {
      result.insert(.glutenFree)
    }
    if restrictions.contains("low_carb") {
      result.insert(.lowCarb)
    }

    return result
  }
}

// MARK: - Substitution Entry

/// A single ingredient substitution: replace `originalId` with `substituteId`.
struct Substitution: Sendable, Identifiable {
  var id: String { "\(originalId)-\(substituteId)" }
  let originalId: Int64
  let substituteId: Int64
  /// The canonical key the substitute resolves to — the composition and table
  /// identity the offer came from. Empty only for hand-built offers.
  let substituteKey: String
  let reasons: Set<SubstitutionReason>
  /// Gram-for-gram ratio. 1.0 = same weight. e.g. 0.8 means use 80% of the original weight.
  let ratio: Double

  /// Human-readable note for the cook.
  let note: String?
}

// MARK: - Screened Substitution Entry

/// A substitution with its per-eater composition screen outcome, for callers
/// that surface ask-the-user states instead of silently dropping the swap.
struct ScreenedSubstitution: Sendable, Identifiable {
  var id: String { swap.id }
  let swap: Substitution
  /// CompositionScreen for the queried restrictions:
  /// `.allowed`, `.askUser` (unknown composition — check the label), or
  /// `.refused(offending:)` with the offending allergen/diet classes.
  let screen: CompositionScreen
}

// MARK: - Substitution Service

/// Pure-logic service over the reviewed, context-specific substitution table
/// (`Substitutions/substitutions-v2.json`, generated by
/// `scripts/substitutions/convert.py` from the overhaul branch's reviewed
/// `pairs.json` against the canonical ingredient vocabulary).
///
/// Schema v2 swaps are keyed by canonical ingredient keys, not app ingredient
/// ids. This service maps between the two through the catalog identity bridge
/// (`recipes_catalog_ingredient_bridge`, rebuilt during hydration from the
/// vocabulary's legacy links and FDC evidence). An app ingredient id resolves
/// to the canonical key(s) it stands for; a substitute key resolves back to
/// the app ingredient row it can swap into the pantry line. Unresolved
/// endpoints simply yield no offer — nothing is guessed by name similarity.
///
/// No database writes — the table ships with the app bundle. A swap is
/// offered only when its substitute's composition screens clean for the
/// active restrictions; unknown composition fails closed to ask-the-user
/// (SPEC overhaul-20261011 §3.1/§3.5).
final class SubstitutionService: Sendable {
  private let db: DatabaseQueue
  private let userData: UserDataRepository

  /// The reviewed table, indexed by canonical original key.
  private let table: SubstitutionTable?

  /// Canonical keys each app ingredient id stands for, and the app ingredient
  /// ids each canonical key can swap into. Both directions come from the
  /// identity bridge; empty maps mean "unresolvable" — offers disappear.
  ///
  /// The maps are read fresh on every query instead of snapshotted at init:
  /// the service is built before catalog hydration, and the bridge does not
  /// exist yet at that point — an init-time snapshot stayed empty for the
  /// whole launch and no swap was ever offered.
  init(db: DatabaseQueue) {
    self.db = db
    self.userData = UserDataRepository(db: db)
    self.table = Self.loadTable()
  }

  /// Reads the identity bridge now.
  private func bridge() -> Bridged {
    Self.loadBridge(db: db)
  }

  // MARK: - Queries

  /// All substitutes for a given ingredient, screened for the user's dietary
  /// context. Swaps whose substitute violates an active restriction are
  /// omitted; swaps with unknown composition are omitted too (fail closed —
  /// use `screenedSubstitutions` to surface ask-the-user states). When
  /// `dietaryRestrictions` is non-empty, relevant swaps sort first.
  func substitutions(
    for ingredientId: Int64,
    dietaryRestrictions: Set<String> = []
  ) -> [Substitution] {
    guard let table else { return [] }
    let offers = offerableSwaps(
      for: ingredientId, dietaryRestrictions: dietaryRestrictions, table: table)
    return offers
      .map { key, substituteAppId, swap, _ in
        Self.legacyEntry(
          for: swap, originalId: ingredientId, substituteAppId: substituteAppId,
          substituteKey: key, table: table, dietaryRestrictions: dietaryRestrictions)
      }
      .sorted { a, b in
        if dietaryRestrictions.isEmpty { return a.substituteId < b.substituteId }
        let relevant = SubstitutionReason.reasons(forRestrictions: dietaryRestrictions)
        let aRelevant = !a.reasons.isDisjoint(with: relevant)
        let bRelevant = !b.reasons.isDisjoint(with: relevant)
        if aRelevant != bRelevant { return aRelevant }
        return a.substituteId < b.substituteId
      }
  }

  /// Every reviewed swap for an ingredient with its screen outcome, so the
  /// UI can show ask-the-user rows (unknown composition) explicitly.
  func screenedSubstitutions(
    for ingredientId: Int64,
    dietaryRestrictions: Set<String> = []
  ) -> [ScreenedSubstitution] {
    guard let table else { return [] }
    return offerableSwaps(
      for: ingredientId, dietaryRestrictions: dietaryRestrictions, table: table)
      .map { substituteKey, substituteAppId, swap, screen in
        ScreenedSubstitution(
          swap: Self.legacyEntry(
            for: swap, originalId: ingredientId, substituteAppId: substituteAppId,
            substituteKey: substituteKey, table: table,
            dietaryRestrictions: dietaryRestrictions),
          screen: screen)
      }
  }

  /// Quick check: does this ingredient have any substitution?
  func hasSubstitutions(for ingredientId: Int64) -> Bool {
    guard let table else { return false }
    return !offerableSwaps(
      for: ingredientId, dietaryRestrictions: [], table: table).isEmpty
  }

  /// The allergen re-check the cook flow applies before executing a swap
  /// (LeChef §7). Resolves the substitute's canonical keys through the bridge
  /// and screens their composition against the household's active
  /// restrictions:
  ///
  /// - `false` — composition is known and no active restriction forbids a
  ///   class the substitute carries; the swap may execute.
  /// - `true` — a known composition carries a forbidden class; the swap is
  ///   refused with the transcript showing it.
  /// - `nil` — the household profile cannot be read, or the composition
  ///   cannot be settled (unmapped substitute, or the table's fail-closed
  ///   unknown); the swap blocks.
  ///
  /// The household's explicit exclusions — the persisted allergen ingredient
  /// ids plus the diet's excluded ingredient ids — block the substitute before
  /// composition screening, whether or not a diet restriction is active.
  /// Most restrictive wins when a substitute resolves to several keys.
  func substituteIsAllergen(for substituteId: Int64) -> Bool? {
    guard let table else { return nil }

    // A failed profile read is not "no restrictions" — fail closed: the
    // caller treats nil as blocked.
    guard let profile = try? userData.fetchHealthProfile() else { return nil }

    let excluded = Set(profile.parsedAllergenIds).union(profile.dietaryExcludedIngredientIds)
    if excluded.contains(substituteId) { return true }

    let restrictions = profile.normalizedDietaryRestrictionIDs
    guard !restrictions.isEmpty else { return false }

    let keysByAppID = bridge().keysByAppID
    var sawUnknown = false
    for key in keysByAppID[substituteId]?.sorted() ?? [] {
      guard let composition = table.document.compositions[key] else {
        sawUnknown = true
        continue
      }
      guard composition.compositionKnown else {
        sawUnknown = true
        continue
      }
      let carried = Set(composition.allergenClasses).union(composition.dietClasses)
      var forbidden = Set<String>()
      for restriction in restrictions.map(SubstitutionTable.canonicalRestriction) {
        guard let screen = table.document.restrictions[restriction] else { continue }
        forbidden.formUnion(carried.intersection(screen.forbids))
      }
      if !forbidden.isEmpty { return true }
    }
    return sawUnknown ? nil : false
  }

  /// Fetch the `Ingredient` model for a substitute ID (for nutritional comparison).
  func ingredient(id: Int64) throws -> Ingredient? {
    try db.read { db in
      try Ingredient.fetchOne(db, key: id)
    }
  }

  /// The loaded table, for callers that want audit coverage or verdicts.
  var substitutionTable: SubstitutionTable? { table }

  // MARK: - Offer Assembly

  /// The swaps the service can actually offer for an app ingredient line:
  /// resolve the line's canonical keys, take each key's reviewed swaps, and
  /// keep the ones whose substitute key bridges back to an app ingredient
  /// row (min id for determinism — the bridge can resolve a key to several
  /// rows through source aliases). Screens run per swap with the queried
  /// restrictions; the outcome rides along. Deterministic: sorted by
  /// (pairId, substitute key).
  private func offerableSwaps(
    for ingredientId: Int64,
    dietaryRestrictions: Set<String>,
    table: SubstitutionTable
  ) -> [(substituteKey: String, substituteAppId: Int64, swap: SubstitutionSwap, screen: CompositionScreen)] {
    var byPairID: [String: (String, Int64, SubstitutionSwap, CompositionScreen)] = [:]
    let bridged = bridge()
    for originalKey in (bridged.keysByAppID[ingredientId] ?? []).sorted() {
      for (swap, screen) in table.screenedSwaps(
        forCanonical: originalKey, restrictions: dietaryRestrictions)
      {
        guard let substituteAppId = bridged.appIDsByKey[swap.substituteKey]?.min() else { continue }
        if byPairID[swap.pairId] == nil {
          byPairID[swap.pairId] = (swap.substituteKey, substituteAppId, swap, screen)
        }
      }
    }
    return byPairID
      .map { $0.value }
      .sorted { a, b in
        if a.swap.pairId != b.swap.pairId { return a.swap.pairId < b.swap.pairId }
        return a.substituteKey < b.substituteKey
      }
  }

  // MARK: - Bundled Table

  /// Loads the reviewed table from the app bundle. A missing or undecodable
  /// resource leaves the service empty rather than crashing: substitutions
  /// disappear, nothing wrong is offered.
  private static func loadTable() -> SubstitutionTable? {
    let url =
      Bundle.main.url(forResource: "substitutions-v2", withExtension: "json")
      ?? Bundle.main.url(
        forResource: "substitutions-v2", withExtension: "json",
        subdirectory: "Substitutions")
    guard let url else {
      assertionFailure("substitutions-v2.json not found in bundle")
      return nil
    }
    do {
      let data = try Data(contentsOf: url)
      return try SubstitutionTable(data: data)
    } catch {
      assertionFailure("Failed to load substitutions-v2.json: \(error)")
      return nil
    }
  }

  // MARK: - Identity Bridge

  private struct Bridged: Sendable {
    let keysByAppID: [Int64: Set<String>]
    let appIDsByKey: [String: Set<Int64>]
  }

  /// Reads the catalog identity bridge into memory. The bridge is small
  /// (hundreds of rows), so reading it per query costs little and stays
  /// correct whenever hydration completes after this service was built — the
  /// launch order is: AppDependencies builds the service first, then
  /// `warmBundledContentIfNeeded()` hydrates the catalog and rebuilds the
  /// bridge. An absent table (fresh installs before hydration, some test
  /// environments) yields empty maps: no offers, no guesses.
  private static func loadBridge(db: DatabaseQueue) -> Bridged {
    var keysByAppID: [Int64: Set<String>] = [:]
    var appIDsByKey: [String: Set<Int64>] = [:]
    let rows = try? db.read { db in
      try Row.fetchAll(
        db,
        sql: "SELECT ingredient_key, ingredient_id FROM recipes_catalog_ingredient_bridge")
    }
    for row in rows ?? [] {
      guard let key: String = row["ingredient_key"], let id: Int64 = row["ingredient_id"]
      else { continue }
      keysByAppID[id, default: []].insert(key)
      appIDsByKey[key, default: []].insert(id)
    }
    return Bridged(keysByAppID: keysByAppID, appIDsByKey: appIDsByKey)
  }

  // MARK: - Legacy Entry Mapping

  /// Maps a reviewed swap onto the legacy `Substitution` shape the sheet
  /// consumes. Reasons are derived from the queried dietary context; the
  /// note carries the difference, the preparation, and the scaling statement.
  private static func legacyEntry(
    for swap: SubstitutionSwap,
    originalId: Int64,
    substituteAppId: Int64,
    substituteKey: String,
    table: SubstitutionTable,
    dietaryRestrictions: Set<String>
  ) -> Substitution {
    var reasons = Set<SubstitutionReason>()
    let relevant = SubstitutionReason.reasons(forRestrictions: dietaryRestrictions)
    if relevant.contains(.vegan) || relevant.contains(.dairyFree) {
      // The screen already established the swap is allowed for these
      // restrictions; tag it so relevant swaps sort first.
      reasons.insert(.vegan)
      reasons.insert(.dairyFree)
    }
    if relevant.contains(.vegetarian) { reasons.insert(.vegetarian) }
    if relevant.contains(.glutenFree) { reasons.insert(.glutenFree) }
    if relevant.contains(.lowCarb) { reasons.insert(.lowCarb) }
    if reasons.isEmpty { reasons.insert(.similar) }

    var notes: [String] = [swap.difference]
    if let ratio = swap.ratio {
      if ratio.scales {
        notes.append(
          "Use \(Int((ratio.value * 100).rounded()))% of the original weight.")
      } else {
        notes.append("Measure per the kitchen statement: \(ratio.basis).")
      }
      if let note = ratio.note { notes.append(note) }
    }
    notes.append(contentsOf: swap.preparation)

    return Substitution(
      originalId: originalId,
      substituteId: substituteAppId,
      substituteKey: substituteKey,
      reasons: reasons,
      ratio: swap.ratio?.value ?? 1.0,
      note: notes.joined(separator: " ")
    )
  }
}
