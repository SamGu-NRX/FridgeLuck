#!/usr/bin/env python3
"""Render the Swift fixture for the substitution evidence replay tests.

Reads evidence/pairs.snapshot.json and writes
apps/ios/Tests/SubstitutionEvidencePairs+Generated.swift — a generated Swift
file holding the frozen production pairs and the source-region SHA-256, so the
Swift replay tests can compare the live SubstitutionService.swift source
against the evidence set without shipping resources.

Deterministic: same snapshot -> byte-identical Swift file.

Usage:
    python3 tools/render_swift_fixture.py [--snapshot PATH] [--out PATH]
"""
import argparse
import json
import sys
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parent

HEADER = """\
// Generated by apps/ios/Tools/substitution-eval/tools/render_swift_fixture.py
// from evidence/pairs.snapshot.json. DO NOT EDIT by hand — rerun the script.

import Foundation

/// One production substitution pair, frozen from SubstitutionService.swift.
struct SubstitutionEvidencePair: Equatable {
  let originalId: Int
  let substituteId: Int
  let ratio: Double
  let reasons: [String]
}

enum SubstitutionEvidenceSnapshot {
  static let sourceRegionSHA256 = "@@SHA@@"
  static let pairs: [SubstitutionEvidencePair] = [
@@PAIRS@@
  ]
}
"""

CONTEXTS_HEADER = """\
// Generated by apps/ios/Tools/substitution-eval/tools/render_swift_fixture.py
// from evidence/context_cases.csv. DO NOT EDIT by hand — rerun the script.

/// One (pair, bundled recipe) context case from the evidence harness.
struct SubstitutionEvidenceContext: Equatable {
  let caseId: String
  let originalId: Int
  let substituteId: Int
  let recipeId: Int
  let ingredientRole: String
  let contextFunction: String
  let verdict: String
  let productionRatio: Double
}

enum SubstitutionEvidenceContexts {
  static let all: [SubstitutionEvidenceContext] = [
@@CONTEXTS@@
  ]
}
"""


def render(snapshot: dict) -> str:
    pair_lines = []
    for p in snapshot["pairs"]:
        reasons = ", ".join(f'"{r}"' for r in p["reasons"])
        pair_lines.append(
            "    SubstitutionEvidencePair(originalId: %d, substituteId: %d, "
            "ratio: %s, reasons: [%s]),"
            % (p["originalId"], p["substituteId"], repr(float(p["ratio"])), reasons)
        )
    return HEADER.replace("@@SHA@@", snapshot["source_region_sha256"]).replace(
        "@@PAIRS@@", "\n".join(pair_lines)
    )


def render_contexts(contexts: list[dict]) -> str:
    lines = []
    for c in contexts:
        lines.append(
            '    SubstitutionEvidenceContext(caseId: "%s", originalId: %d, substituteId: %d, '
            "recipeId: %d, ingredientRole: \"%s\", contextFunction: \"%s\", verdict: \"%s\", "
            "productionRatio: %s),"
            % (
                c["case_id"], int(c["original_id"]), int(c["substitute_id"]),
                int(c["recipe_id"]), c["ingredient_role"], c["context_function"],
                c["verdict"], repr(float(c["production_ratio"])),
            )
        )
    return CONTEXTS_HEADER.replace("@@CONTEXTS@@", "\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--snapshot",
        default=str(TOOL_DIR / ".." / "evidence" / "pairs.snapshot.json"),
    )
    ap.add_argument(
        "--contexts",
        default=str(TOOL_DIR / ".." / "evidence" / "context_cases.csv"),
    )
    ap.add_argument(
        "--out",
        default=str(TOOL_DIR / ".." / ".." / ".." / "Tests" / "SubstitutionEvidencePairs+Generated.swift"),
    )
    ap.add_argument(
        "--contexts-out",
        default=str(TOOL_DIR / ".." / ".." / ".." / "Tests" / "SubstitutionEvidenceContexts+Generated.swift"),
    )
    args = ap.parse_args()

    snapshot = json.loads(Path(args.snapshot).read_text(encoding="utf-8"))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(snapshot), encoding="utf-8")
    print(f"wrote {out}: {len(snapshot['pairs'])} pairs")

    import csv  # noqa: PLC0415

    with open(args.contexts, newline="", encoding="utf-8") as f:
        contexts = list(csv.DictReader(f))
    ctx_out = Path(args.contexts_out)
    ctx_out.write_text(render_contexts(contexts), encoding="utf-8")
    print(f"wrote {ctx_out}: {len(contexts)} contexts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
