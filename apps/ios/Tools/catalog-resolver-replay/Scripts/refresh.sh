#!/usr/bin/env bash
# Re-sync the mirrored production resolver and regenerate the source manifest.
# The mirror is committed byte-identical; this script is how it stays that way.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$SCRIPT_DIR/../../../../.."
MIRROR="$SCRIPT_DIR/../Sources/CatalogReplayCore/ProductionMirror"
UPSTREAM_REL="apps/ios/Capability/Core/Recognition/IngredientCatalogResolver.swift"

if [ ! -f "$ROOT/$UPSTREAM_REL" ]; then
  echo "error: $UPSTREAM_REL not found under $ROOT" >&2
  exit 1
fi

hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  else
    shasum -a 256 "$1" | cut -d' ' -f1
  fi
}

mkdir -p "$MIRROR"
cp "$ROOT/$UPSTREAM_REL" "$MIRROR/IngredientCatalogResolver.swift"
SHA="$(hash_file "$MIRROR/IngredientCatalogResolver.swift")"

cat > "$MIRROR/SourceManifest.swift" <<SWIFT_MANIFEST
// Generated by Scripts/refresh.sh — do not edit by hand.
// Pins the byte-identical copy of the production resolver.

enum SourceManifest {
  /// Repository path of the production source this mirror copies.
  static let upstream = "$UPSTREAM_REL"

  /// sha256 of each mirrored file, keyed by file name.
  static let sha256: [String: String] = [
    "IngredientCatalogResolver.swift": "$SHA",
  ]
}
SWIFT_MANIFEST
echo "refreshed mirror (IngredientCatalogResolver.swift sha256=$SHA)"
