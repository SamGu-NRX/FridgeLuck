#!/usr/bin/env python3
"""Preprocess ConfidenceLearningService.swift for the Linux runner.

Strips `import os` (no os module in the Linux toolchain) and prepends a
minimal compile-time Logger shim matching the small surface the service uses:
`Logger(subsystem:category:)`, `.info/.debug(_ message: String, privacy: .public)`.
Purely mechanical: the service body is untouched.
"""
import re
import sys
from pathlib import Path

SHIM = '''// BEGIN Linux logger shim (generated by preprocess_learner.py; not part of the
// product source). Minimal stand-in for Apple's os.Logger: logging is a no-op.
public struct OSLogPrivacy {
  public static let `public` = OSLogPrivacy()
  public static let `private` = OSLogPrivacy()
}
public struct Logger {
  public init(subsystem: String, category: String) {}
  public func info(_ message: String, privacy: OSLogPrivacy = .public) {}
  public func debug(_ message: String, privacy: OSLogPrivacy = .public) {}
}
// END Linux logger shim

'''

source = Path(sys.argv[1])
out = Path(sys.argv[2])
lines = source.read_text().split('\n')
stripped = [line for line in lines if line.strip() != 'import os']
# os-style string interpolation `\(expr, privacy: .public)` is not valid String
# interpolation; the shim's logging is a no-op, so drop the privacy argument.
text = '\n'.join(stripped)
text = re.sub(r',\s*privacy:\s*\.public\)', ')', text)
out.write_text(SHIM + text)
print(f'{source} -> {out} (os import stripped, privacy args stripped, shim injected)')
